// Command versiongen writes the public target-version constants from the
// checked-in source lock.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

var versionPattern = regexp.MustCompile(`^2\.[0-9]+\.[0-9]+$`)

func main() {
	var lockPath string
	var root string
	flag.StringVar(&lockPath, "lock", "source.lock.json", "path to source lock")
	flag.StringVar(&root, "root", ".", "repository root")
	flag.Parse()

	data, err := os.ReadFile(lockPath)
	if err != nil {
		fail(err)
	}
	var lock struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal(data, &lock); err != nil {
		fail(err)
	}
	if !versionPattern.MatchString(lock.Version) {
		fail(fmt.Errorf("invalid version %q", lock.Version))
	}

	write(filepath.Join(root, "pkg/nifi/version.gen.go"), "nifi", "TargetNiFiVersion", lock.Version)
	write(filepath.Join(root, "pkg/registry/version.gen.go"), "registry", "TargetRegistryVersion", lock.Version)
}

func write(path, packageName, constant, version string) {
	content := fmt.Sprintf(`// Code generated by versiongen; DO NOT EDIT.

package %s

// %s is the exact Apache NiFi%s version represented by this binding release.
const %s = %q
`, packageName, constant, map[bool]string{true: " Registry"}[packageName == "registry"], constant, version)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "versiongen:", err)
	os.Exit(1)
}
